use std::path::{Path, PathBuf};

use subforge_core::lines::{
    arabic_punctuation, extract_lines, fix_rtl_text, is_drawing, plain_text, rebuild_lines, reflow,
    SubtitleLine,
};
use subforge_core::subtitle::{load, Cue};

fn lines_fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/lines")
        .join(name)
}

fn sub_fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/subtitles")
        .join(name)
}

fn translations(name: &str) -> Vec<String> {
    serde_json::from_str(&std::fs::read_to_string(lines_fixture(name)).unwrap()).unwrap()
}

fn load_cues(path: &Path) -> Vec<Cue> {
    load(path).unwrap().cues
}

// ---- ported from scripts/test_subtitle_lines.py ----

#[test]
fn plain_text_strips_tags_and_joins_breaks() {
    assert_eq!(
        plain_text(r"{\i1}An encounter swallows{\i0}\N{\i1}me up{\i0}"),
        "An encounter swallows me up"
    );
    assert_eq!(plain_text(r"{\an8}Hello\Nthere"), "Hello there");
    assert_eq!(plain_text(r"{\p1}m 0 0 l 10 10{\p0}"), "");
    assert!(is_drawing(r"{\p1}m 0 0{\p0}"));
    assert!(!is_drawing(r"{\pos(1,2)}hi"));
}

#[test]
fn reflow_keeps_italics_and_position() {
    let out = reflow(r"{\an8}{\i1}Hello{\i0}\N{\i1}there{\i0}", "مرحبا بكم جميعا");
    assert!(out.starts_with(r"{\an8}"));
    assert!(out.contains(r"{\i1}") && out.contains(r"{\i0}"));
    assert_eq!(out.matches('\n').count(), 1);
}

#[test]
fn reflow_dash_dialogue() {
    let out = reflow(r"- Where?\N- Home.", "- أين؟ - إلى البيت.");
    assert_eq!(
        out.split('\n').collect::<Vec<_>>(),
        ["- أين؟", "- إلى البيت."]
    );
}

#[test]
fn reflow_wraps_long_single_line() {
    let out = reflow("Short", &"كلمة ".repeat(20));
    assert!(out.contains('\n'));
    assert!(out.split('\n').all(|p| p.chars().count() <= 60));
}

#[test]
fn reflow_plain_not_italic() {
    assert_eq!(reflow("Hello", "مرحبا"), "مرحبا");
}

#[test]
fn arabic_punctuation_converts_latin_marks() {
    assert_eq!(
        arabic_punctuation("ماذا, هل؟ لا; نعم?"),
        "ماذا\u{60c} هل؟ لا\u{61b} نعم\u{61f}"
    );
    assert_eq!(arabic_punctuation("مبلغ 1,000 ريال"), "مبلغ 1,000 ريال");
    assert_eq!(arabic_punctuation("What? Yes, no"), "What? Yes, no");
}

// ---- extra unit coverage ----

#[test]
fn arabic_punctuation_comma_next_to_one_digit() {
    // Only commas between two digits are kept.
    assert_eq!(arabic_punctuation("عدد 5, ثم"), "عدد 5\u{60c} ثم");
    assert_eq!(arabic_punctuation("ثم ,5 عدد"), "ثم \u{60c}5 عدد");
}

#[test]
fn fix_rtl_wraps_each_line_and_keeps_leading_tags_outside() {
    let out = fix_rtl_text("{\\an8}مرحبا\nسلام");
    assert_eq!(out, "{\\an8}\u{202b}مرحبا\u{202c}\n\u{202b}سلام\u{202c}");
    // Idempotent, and Latin lines are left alone.
    assert_eq!(fix_rtl_text(&out), out);
    assert_eq!(fix_rtl_text("Hello"), "Hello");
}

#[test]
fn reflow_leading_tags_drop_italic_toggles_but_keep_position() {
    let out = reflow(r"{\an8\i1}Hi{\i0}", "مرحبا");
    assert_eq!(out, "{\\an8}{\\i1}مرحبا{\\i0}");
}

