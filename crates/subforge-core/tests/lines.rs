#[test]
fn extract_gives_comment_cues_empty_text() {
    let lines = extract_lines(&sub_fixture("arabic_full.ass")).unwrap();
    assert_eq!(lines.len(), 6);
    assert_eq!(
        lines[2].text, "",
        "Python sent the Comment line for translation"
    );
    assert_eq!(lines[4].text, "", "drawings stay empty");
}

#[test]
fn rebuild_leaves_comment_cues_untouched() {
    let dir = tempfile::tempdir().unwrap();
    let out = dir.path().join("out.ass");
    rebuild_lines(
        &sub_fixture("arabic_full.ass"),
        &translations("translations_arabic_full.json"),
        &out,
        true,
    )
    .unwrap();
    let cues = load_cues(&out);
    assert!(cues[2].comment);
    assert_eq!(cues[2].text, "ملاحظة المترجم", "Python wrapped it in RLE");
}

#[test]
fn rebuild_preserves_ass_header_fonts_and_section_order() {
    let dir = tempfile::tempdir().unwrap();
    let out = dir.path().join("out.ass");
    rebuild_lines(
        &sub_fixture("arabic_full.ass"),
        &translations("translations_arabic_full.json"),
        &out,
        true,
    )
    .unwrap();
    let text = std::fs::read_to_string(&out).unwrap();
    assert!(text.contains("; Script generated by SubForge test fixtures"));
    assert!(!text.contains("pysubs2"));
    assert!(text.contains("[Fonts]"));
    assert!(text.contains("Style: Top,Noto Naskh Arabic,40,"));
    // pysubs2 moved [Events] after [Fonts]; Rust keeps the original order.
    assert!(text.find("[Events]").unwrap() < text.find("[Fonts]").unwrap());
}

#[test]
fn rebuild_skips_drawings_blank_and_missing_translations() {
    let dir = tempfile::tempdir().unwrap();
    let out = dir.path().join("out.ass");
    let mut tr = translations("translations_arabic_full.json");
    tr[0] = "   ".into();
    tr.truncate(5);
    rebuild_lines(&sub_fixture("arabic_full.ass"), &tr, &out, false).unwrap();
    let cues = load_cues(&out);
    assert_eq!(
        cues[0].text, "مرحبا بالعالم",
        "blank translation keeps original"
    );
    assert!(cues[4].text.starts_with("{\\p1}"), "drawing untouched");
    assert!(
        cues[5].text.starts_with("السلام عليكم ورحمة الله"),
        "index past the translations keeps original"
    );
    assert!(!cues[5].text.contains("وبركاته"));
}

// ---- parity with the frozen Python output ----

fn check_extract(source: &Path, expected: &str, ignore_ids: &[usize]) {
    let got = extract_lines(source).unwrap();
    let want: Vec<SubtitleLine> =
        serde_json::from_str(&std::fs::read_to_string(lines_fixture(expected)).unwrap()).unwrap();
    assert_eq!(got.len(), want.len());
    for (g, w) in got.iter().zip(&want) {
        assert_eq!((g.id, g.start, g.end), (w.id, w.start, w.end));
        if !ignore_ids.contains(&g.id) {
            assert_eq!(g.text, w.text, "cue {}", g.id);
        }
    }
}

#[test]
fn extract_matches_python_parity() {
    // arabic_full.ass cue 2 is a Comment: documented difference.
    check_extract(
        &sub_fixture("arabic_full.ass"),
        "arabic_full.extract.expected",
        &[2],
    );
    check_extract(&sub_fixture("basic.srt"), "basic.extract.expected", &[]);
    check_extract(&lines_fixture("dash.srt"), "dash.extract.expected", &[]);
}

fn check_rebuild(source: &Path, tr: &str, expected: &str, ext: &str, skip_comments: bool) {
    let dir = tempfile::tempdir().unwrap();
    let out = dir.path().join(format!("out.{ext}"));
    rebuild_lines(source, &translations(tr), &out, true).unwrap();
    let got = load_cues(&out);
    let want = load_cues(&lines_fixture(expected));
    assert_eq!(got.len(), want.len());
    for (i, (g, w)) in got.iter().zip(&want).enumerate() {
        assert_eq!((g.start_ms, g.end_ms), (w.start_ms, w.end_ms), "cue {i}");
        if skip_comments && g.comment {
            continue;
        }
        assert_eq!(g.text, w.text, "cue {i}");
    }
}

#[test]
